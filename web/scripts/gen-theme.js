// Writes app/theme.css: every colour Tailwind uses as an "R G B" CSS variable, once for
// the dark theme (the default) and once for the light theme (html[data-theme="light"]).
// tailwind.config.js reads the same list (lib/themeColors.js). Run: node scripts/gen-theme.js
const fs = require('fs');
const path = require('path');
const { DARK, LIGHT } = require('../lib/themeColors');

const rgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
};
const block = (sel, map) => `${sel} {\n${Object.entries(map).map(([k, v]) => `  --tw-c-${k}: ${rgb(v)};`).join('\n')}\n}\n`;

const out =
  `/* Generated by scripts/gen-theme.js — do not edit by hand. */\n` +
  block(':root,\n.theme-dark,\nhtml[data-theme="light"] .theme-dark', DARK) +
  '\n' +
  block('html[data-theme="light"]', LIGHT);
fs.writeFileSync(path.join(__dirname, '../app/theme.css'), out);
console.log('app/theme.css', Object.keys(DARK).length, 'colours');
